/**
 * CeTZ serializer checks.
 *
 * These run without a Typst compiler: they assert the structural contract that
 * the live WASM preview and a real Typst 0.15 + CeTZ 0.5.3 build both rely on.
 * The browser verification covers actual compilation for all six fixtures.
 */

import { STEP1_FIXTURES } from "../src/fixtures/index.ts";
import { buildLayoutSnapshot } from "../src/layout/build-layout.ts";
import { FixedTextMeasurer } from "../src/layout/text.ts";
import { serializeSceneToCetz } from "../src/export/cetz.ts";
import {
  DEFAULT_EXPORT_SETTINGS,
  pageSize,
  type ExportSettings,
  type PageSpec,
} from "../src/export/page.ts";
import type { SceneDocument } from "../src/model/scene.ts";
import type { SceneNode } from "../src/model/nodes.ts";

let passed = 0;
const failures: string[] = [];

const check = (condition: boolean, message: string): void => {
  if (condition) {
    passed += 1;
  } else {
    failures.push(message);
  }
};

const settings = (patch: Partial<ExportSettings> = {}): ExportSettings => ({
  ...DEFAULT_EXPORT_SETTINGS,
  diagramId: "fig-test",
  ...patch,
  page: patch.page ?? DEFAULT_EXPORT_SETTINGS.page,
});

const measurer = new FixedTextMeasurer();

const serialize = (
  scene: SceneDocument,
  options: {
    readonly settings?: Partial<ExportSettings>;
    readonly selectedNodeIds?: readonly string[];
    readonly selectedEdgeId?: string | null;
  } = {},
) => {
  const layout = buildLayoutSnapshot(scene, measurer);
  return serializeSceneToCetz({
    scene,
    layout,
    settings: settings(options.settings),
    selectedNodeIds: options.selectedNodeIds ?? [],
    selectedEdgeId: options.selectedEdgeId ?? null,
  });
};

const nodeByName = (scene: SceneDocument, name: string): SceneNode => {
  const node = Object.values(scene.nodes).find((candidate) => candidate.name === name);
  if (node === undefined) throw new Error(`Missing fixture node ${name}`);
  return node;
};

const balanced = (code: string): boolean => {
  let braces = 0;
  let brackets = 0;
  let parens = 0;
  let inString = false;
  let escaped = false;
  for (const character of code) {
    if (inString) {
      if (escaped) escaped = false;
      else if (character === "\\") escaped = true;
      else if (character === '"') inString = false;
      continue;
    }
    if (character === '"') inString = true;
    else if (character === "{") braces += 1;
    else if (character === "}") braces -= 1;
    else if (character === "[") brackets += 1;
    else if (character === "]") brackets -= 1;
    else if (character === "(") parens += 1;
    else if (character === ")") parens -= 1;
    if (braces < 0 || brackets < 0 || parens < 0) return false;
  }
  return braces === 0 && brackets === 0 && parens === 0 && !inString;
};

// ---------------------------------------------------------------------------
// Every fixture produces a complete page wrapper and a balanced canvas body.
// ---------------------------------------------------------------------------
for (const fixture of STEP1_FIXTURES) {
  const result = serialize(fixture.scene);
  const code = result.code;
  check(!code.includes("Generated by UMLer"), `${fixture.scene.meta.title}: no banner`);
  check(!code.includes("#import"), `${fixture.scene.meta.title}: no import in result`);
  check(!code.includes("#set page"), `${fixture.scene.meta.title}: no page setter`);
  check(!code.includes("#set text"), `${fixture.scene.meta.title}: no global text setter`);
  check(
    !code.includes('font: ("Latin Modern Roman"'),
    `${fixture.scene.meta.title}: body text inherits the document font`,
  );
  check(
    result.previewCode.includes('#import "@preview/cetz:0.5.2": canvas, draw'),
    `${fixture.scene.meta.title}: preview import`,
  );
  check(result.previewCode.includes("#set page("), `${fixture.scene.meta.title}: preview page`);
  check(code.startsWith("#figure("), `${fixture.scene.meta.title}: starts with figure`);
  check(code.includes("#canvas(length: 1pt"), `${fixture.scene.meta.title}: canvas`);
  check(code.includes("<fig-test>"), `${fixture.scene.meta.title}: label`);
  check(code.endsWith("\n"), `${fixture.scene.meta.title}: trailing newline`);
  check(balanced(code), `${fixture.scene.meta.title}: balanced delimiters`);
  check(!code.includes("data-editor-only"), `${fixture.scene.meta.title}: no editor overlay`);
  check(!code.includes("lock-badge"), `${fixture.scene.meta.title}: no lock badge`);
  check(
    result.stats.nodes === Object.values(fixture.scene.nodes).filter((node) => node.visible !== false).length,
    `${fixture.scene.meta.title}: node count`,
  );
  check(
    result.stats.edges === Object.values(fixture.scene.edges).filter((edge) => edge.visible !== false).length,
    `${fixture.scene.meta.title}: edge count`,
  );
  if (result.stats.marks > 0) {
    check(code.includes("draw.register-mark("), `${fixture.scene.meta.title}: marks registered`);
  }
}

// ---------------------------------------------------------------------------
// Page fitting: never stretch implicitly, always fit down, honour explicit zoom.
// ---------------------------------------------------------------------------
const er = STEP1_FIXTURES.find((fixture) => fixture.scene.meta.diagramKind === "er");
if (er === undefined) throw new Error("ER fixture missing");
const customers = nodeByName(er.scene, "customers");
const orders = nodeByName(er.scene, "orders");

const single = serialize(er.scene, { selectedNodeIds: [customers.id], settings: { scope: "selection" } });
check(single.selection.nodes.length === 1, "single selection resolves one node");
check(single.fit.scale === 1, "small selection is not stretched to the page");
check(single.selection.naturalWidth < 595, "small selection is narrower than A4");
check(single.selection.edges.length === 0, "single selection omits unselected connectors");

const multi = serialize(er.scene, {
  selectedNodeIds: [customers.id, orders.id],
  settings: { scope: "selection" },
});
check(multi.selection.nodes.length === 2, "multi selection resolves two nodes");
check(multi.selection.edges.length === 1, "connector between two selected nodes is included");
check(multi.selection.naturalWidth > single.selection.naturalWidth, "multi selection bounds grow");
check(multi.fit.scale <= 1, "multi selection is not enlarged");

const relationshipEdge = Object.values(er.scene.edges).find(
  (edge) => edge.semantic.family === "er" && edge.semantic.name === "places",
);
check(relationshipEdge !== undefined, "relationship edge exists");
if (relationshipEdge !== undefined) {
  const edgeSelection = serialize(er.scene, {
    selectedEdgeId: relationshipEdge.id,
    settings: { scope: "selection" },
  });
  check(edgeSelection.selection.nodes.length === 2, "edge selection pulls in both endpoint nodes");
  check(edgeSelection.selection.edges.length === 1, "edge selection exports the connector");

  const tetherEdge = Object.values(er.scene.edges).find(
    (edge) => edge.source.target === "edge" || edge.target.target === "edge",
  );
  check(tetherEdge !== undefined, "relation-attribute tether exists");
  if (tetherEdge !== undefined) {
    const tetherSelection = serialize(er.scene, {
      selectedEdgeId: tetherEdge.id,
      settings: { scope: "selection" },
    });
    check(tetherSelection.selection.nodes.length === 3, "tether selection follows its host relationship");
    check(tetherSelection.selection.edges.length === 2, "tether selection includes host and tether");
  }
}

const zoomed = serialize(er.scene, {
  selectedNodeIds: [customers.id],
  settings: { scope: "selection", zoom: 1.5 },
});
check(Math.abs(zoomed.fit.scale - 1.5) < 1e-9, "explicit zoom enlarges a small selection");
check(zoomed.fit.diagramWidthPt > zoomed.selection.naturalWidth, "explicit zoom enlarges the emitted geometry");

const bigPage: PageSpec = {
  preset: "custom",
  customWidth: 2000,
  customHeight: 2000,
  unit: "mm",
};
const huge = serialize(er.scene, { settings: { page: bigPage } });
check(huge.fit.scale === 1, "a huge page does not stretch the diagram");
check(huge.fit.fitLimit > 1, "huge page fit limit is above one");

const tinyPage: PageSpec = {
  preset: "custom",
  customWidth: 80,
  customHeight: 80,
  unit: "mm",
};
const tiny = serialize(er.scene, { settings: { page: tinyPage } });
check(tiny.fit.fitReduced, "tiny page forces a fit-down");
check(tiny.fit.scale < 1, "tiny page scale is below one");
check(tiny.fit.scale * tiny.selection.naturalWidth <= tiny.page.widthPt + 0.01, "fit respects page width");
check(tiny.fit.scale * tiny.selection.naturalHeight <= tiny.fit.availableHeightPt + 0.01, "fit respects page height");

// ---------------------------------------------------------------------------
// Page options and alignment.
// ---------------------------------------------------------------------------
const landscape = serialize(er.scene, {
  settings: { page: { ...DEFAULT_EXPORT_SETTINGS.page, preset: "a4-landscape" } },
});
const landscapeSize = pageSize({ ...DEFAULT_EXPORT_SETTINGS.page, preset: "a4-landscape" });
const fmt = (value: number): string => String(Math.round(value * 1000) / 1000);
check(landscape.previewCode.includes(`width: ${fmt(landscapeSize.widthPt)}pt`), "A4 landscape width");
check(landscape.previewCode.includes(`height: ${fmt(landscapeSize.heightPt)}pt`), "A4 landscape height");
check(!landscape.code.includes("#set page"), "A4 landscape size is preview-only");

const aligned = serialize(er.scene, { settings: { align: "right" } });
check(aligned.code.includes("#align(right)["), "right alignment emitted");
const defaultCaption = serialize(er.scene);
check(defaultCaption.code.includes("caption:"), "scene name is the default label");
check(defaultCaption.code.includes("ER — commerce"), "default label contains the scene name");
const noCaption = serialize(er.scene, { settings: { label: "" } });
check(!noCaption.code.includes("caption:"), "an empty label disables the caption");
check(!noCaption.code.includes("gap: 6pt"), "caption gap removed with the caption");
check(noCaption.code.includes("numbering: none"), "figure numbering stays disabled without a caption");
const customCaption = serialize(er.scene, { settings: { label: "Custom label" } });
check(customCaption.code.includes('Custom label'), "caption text is editable");
const whitespaceCaption = serialize(er.scene, { settings: { label: "   " } });
check(!whitespaceCaption.code.includes("caption:"), "whitespace-only label disables the caption");

// ---------------------------------------------------------------------------
// Diagram IDs, escaping, images.
// ---------------------------------------------------------------------------
const unsafeId = serialize(er.scene, {
  settings: { diagramId: "My Scene/1" },
});
check(unsafeId.label === "fig-my-scene-1", "diagram id is sanitized");
check(unsafeId.code.includes("] <fig-my-scene-1>"), "sanitized id is emitted");

const useCase = STEP1_FIXTURES.find((fixture) => fixture.scene.meta.diagramKind === "uml-use-case");
if (useCase !== undefined) {
  const imageResult = serialize(useCase.scene);
  check(imageResult.code.includes('image("assets/brand.svg"'), "image is a resource reference");
  check(!imageResult.code.includes("data:image"), "binary assets are not embedded");
  check(imageResult.images.length === 1, "image reference collected");
  check(!imageResult.code.includes("Place the referenced image file"), "no resource commentary in source");
  const folder = serialize(useCase.scene, { settings: { resourceFolder: "media/img/" } });
  check(folder.code.includes('image("media/img/brand.svg"'), "resource folder is normalized");
}

// Text that would be Typst markup must render literally through `#("...")`.
const hostile = structuredClone(er.scene) as SceneDocument;
const target = Object.values(hostile.nodes).find((node) => node.name === "customers");
if (target !== undefined) {
  (target as { name: string }).name = 'A]B"C\\D';
}
const escaped = serialize(hostile);
check(escaped.code.includes('\\"C\\\\D'), "quotes and backslashes in text are escaped");
check(escaped.code.includes('[#("A]B\\"C\\\\D")]'), "literal text uses the #(...) escape hatch");

if (failures.length > 0) {
  console.error(`CeTZ serializer checks failed (${failures.length}).`);
  for (const failure of failures) console.error(`  ✗ ${failure}`);
  process.exit(1);
}
console.log(`CeTZ serializer checks passed (${passed} assertions).`);
