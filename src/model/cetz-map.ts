export interface CetzIdentifierRules {
  readonly prefix: "n" | "e" | "label";
  readonly allowed: RegExp;
  readonly separator: "_";
  readonly maxLength: number;
}

export const CETZ_IDENTIFIER_RULES: CetzIdentifierRules = {
  prefix: "n",
  allowed: /^[A-Za-z][A-Za-z0-9_-]*$/,
  separator: "_",
  maxLength: 64,
};

/** FNV-1a; used only to disambiguate a sanitized identifier. */
const hash = (value: string): string => {
  let h = 0x811c9dc5;
  for (let i = 0; i < value.length; i += 1) {
    h ^= value.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return (h >>> 0).toString(36).slice(0, 6);
};

/**
 * Maps a document ID to a Typst identifier. Dots are reserved by CeTZ's anchor
 * syntax, so they are never emitted raw. The hash suffix is added whenever
 * sanitization changes the ID, preventing silent collisions.
 */
export const toCetzName = (prefix: "n" | "e" | "label", id: string): string => {
  const cleaned = id.replace(/[^A-Za-z0-9_-]/g, "_");
  const safe = cleaned.length > 0 && /^[A-Za-z_]/.test(cleaned) ? cleaned : `x_${cleaned}`;
  const needsHash = safe !== id;
  const suffix = needsHash ? `_${hash(id)}` : "";
  return `${prefix}_${safe.slice(0, 48)}${suffix}`;
};

/** Anchor suffix for a resolved port; the node name is prefixed by the emitter. */
export const toCetzAnchorName = (portName: string): string =>
  portName.replace(/[^A-Za-z0-9_-]/g, "_").slice(0, 64);
