/**
 * Machine-readable CeTZ mapping schema.
 *
 * This is the contract Step 4's serializer will implement. It deliberately
 * contains no string-concatenation emitter yet: Step 1 fixes the vocabulary,
 * naming rules and geometry conversion so later phases cannot invent a second
 * source of truth.
 *
 * CeTZ 0.5.3 (the version in `cetz.pdf`) is the target. Note that `ortho` is an
 * orthographic *projection*, not orthogonal edge routing. Orthogonal routes are
 * computed in TypeScript and emitted as a polyline to `line`.
 */

